// Official Skill and Ability (Augment) Data with exact JP costs, Unlock/Require Job Levels, and PP Costs
export interface OfficialParam {
  Lv: number;
  RequireJobLevel: number;
  RequireJobPoint: number;
}

export interface OfficialSkillDef {
  SkillNo: number;
  Job: number;
  Params: OfficialParam[];
}

export interface OfficialAbilityDef {
  AbilityNo: number;
  Job: number;
  Cost: number;
  Params: OfficialParam[];
}

// Compact helper to create Skill Entry
function s(SkillNo: number, Job: number, params: [number, number, number][]): OfficialSkillDef {
  return {
    SkillNo,
    Job,
    Params: params.map(([Lv, RequireJobLevel, RequireJobPoint]) => ({ Lv, RequireJobLevel, RequireJobPoint }))
  };
}

// Compact helper to create Ability Entry
function a(AbilityNo: number, Job: number, Cost: number, params: [number, number, number][]): OfficialAbilityDef {
  return {
    AbilityNo,
    Job,
    Cost,
    Params: params.map(([Lv, RequireJobLevel, RequireJobPoint]) => ({ Lv, RequireJobLevel, RequireJobPoint }))
  };
}

